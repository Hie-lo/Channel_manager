async def seed_default_tutorials(session: AsyncSession) -> int:
    """
    ایجاد یا آپدیت آموزش‌های پیش‌فرض
    اگه آموزش با اون key از قبل باشه، آپدیت میشه
    """
    from app.services.tutorial_service import update_tutorial

    created_count = 0
    updated_count = 0

    for tutorial_data in DEFAULT_TUTORIALS:
        existing = await get_tutorial_by_key(session, tutorial_data["key"])

        if existing:
            # آپدیت آموزش موجود
            # حذف key از kwargs چون update_tutorial بر اساس key کار می‌کنه
            update_data = {k: v for k, v in tutorial_data.items() if k != "key"}
            await update_tutorial(session, key=tutorial_data["key"], **update_data)
            updated_count += 1
        else:
            # ایجاد آموزش جدید
            await create_tutorial(session, **tutorial_data)
            created_count += 1

    if created_count > 0:
        log.info(f"✅ {created_count} آموزش پیش‌فرض ایجاد شد")
    if updated_count > 0:
        log.info(f"🔄 {updated_count} آموزش پیش‌فرض آپدیت شد")

    return created_count + updated_count